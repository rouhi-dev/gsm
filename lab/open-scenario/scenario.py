def waits(m, pr):
    """What a process waits for before it starts (derived from the topology's relationships, not configured twice):
    the servers it must reach at start, and -- osmo-bsc in supervisor mode -- the Supervisor's session socket."""
    e = m["el"][pr["element"]]
    typ, w = e["type"], []
    if typ == "msc":
        st = m["el"][e["stp"]]
        w += [(st.get("transport", "sctp"), f"{addr(m, e['stp'])}:{st['m3ua_port']}"),
              ("tcp", f"{addr(m, e['hlr'])}:{HLR_GSUP_PORT}")]
    elif typ == "bsc":
        st = m["el"][e["stp"]]
        if pr["process"] == "osmo-bsc" and mode_of(m, pr["element"]) == "supervisor":
            w.append(("unix", supervisor_socket(m, pr["element"])))     # its workers (the Supervisor's) use the STP
        else:
            w.append((st.get("transport", "sctp"), f"{addr(m, e['stp'])}:{st['m3ua_port']}"))
    elif typ == "bts-virtual":
        w.append(("tcp", f"{addr(m, e['bsc'])}:{BSC_OML_PORT}"))      # osmo-bts exits when OML cannot connect
    elif typ == "mobile":
        w.append(("unix", processes(m, e["virtphy"])[0]["run"] + "/l2"))
    return w


def q(s):
    return "'" + s.replace("'", "'\\''") + "'"


def tmuxinator_project(m, nid):
    me = os.path.join(HERE, "scenario.py")
    lines = [f"# {GEN_MARK}", f"# node {nid} ({m['nodes'][nid]['host']}, {m['nodes'][nid]['address']}): one window per "
             "process, started in topology order; each waits for what it needs first.",
             f"#   start: tmuxinator start -p {os.path.join(GEN, 'tmuxinator', nid + '.yml')}",
             f"#   stop:  {me} stop {nid}      (processes in reverse order, then the session)",
             f"#   attach: tmux -L {SESSION_SOCKET} attach -t {SESSION_SOCKET}-{nid}",
             f"name: {SESSION_SOCKET}-{nid}", f"root: {HERE}", f"socket_name: {SESSION_SOCKET}",
             "on_project_stop: " + json.dumps(f"python3 {q(me)} stop {nid} --processes-only"), "windows:"]
    for eid in [x for x in m["el"] if m["el"][x]["node"] == nid]:
        for pr in processes(m, eid):
            pre = " && ".join(f"python3 {q(me)} wait-for {k} {q(v)}" for k, v in waits(m, pr))
            env = " ".join(q(f"{k}={v}") for k, v in pr["env"].items())
            cp = f"--copy {q(pr['copy_cfg'])} " if pr["copy_cfg"] else ""
            run = (f"{q(os.path.join(HERE, 'bin', 'run'))} {cp}{q(pr['run'])} {env + ' ' if env else ''}-- "
                   + " ".join(q(x) for x in [pr["program"]] + pr["args"]))
            lines.append(f"  - {pr['window']}: " + json.dumps((pre + " && " if pre else "") + run))
        if m["el"][eid]["type"] == "hlr" and m["el"][eid].get("subscribers"):
            e = m["el"][eid]
            lines.append("  - provision: " + json.dumps(
                f"python3 {q(me)} wait-for tcp {addr(m, eid)}:{e['vty']} && python3 {q(me)} "
                f"vty {addr(m, eid)} {e['vty']} {q(os.path.join(GEN, e['node'], eid + '.provision.vty'))}"))
    return "\n".join(lines) + "\n"


def render_all(m):
    if m["errors"]:
        raise TopologyError("\n".join(m["errors"]))
    out = {}
    for eid, e in m["el"].items():
        if RENDER[e["type"]]:
            out[os.path.join(e["node"], f"{eid}.cfg")] = RENDER[e["type"]](m, eid)
        if e["type"] == "hlr":
            out[os.path.join(e["node"], f"{eid}.provision.vty")] = r_hlr_provision(m, eid)
    for nid in m["nodes"]:
        procs = [dict(pr, wait=waits(m, pr)) for eid in m["el"] if m["el"][eid]["node"] == nid
                 for pr in processes(m, eid)]
        if not procs:
            continue
        out[os.path.join(nid, "processes.json")] = json.dumps(
            {"generated": GEN_MARK, "node": nid, "processes": procs}, indent=1) + "\n"
        out[os.path.join("tmuxinator", f"{nid}.yml")] = tmuxinator_project(m, nid)
    return out


