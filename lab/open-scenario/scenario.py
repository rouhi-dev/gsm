    p.add_argument("nodes", nargs="*")
    p.set_defaults(fn=c_status)
    p = sp.add_parser("stop")
    p.add_argument("node")
    p.add_argument("--processes-only", action="store_true")
    p.set_defaults(fn=c_stop)
