def c_stop(args):
    mf = os.path.join(GEN, args.node, "processes.json")
    if not os.path.isfile(mf):
        print(f"no generated processes for node {args.node}")
        return 1
    procs = json.load(open(mf))["processes"]
    rc = 0
    for pr in reversed(procs):
        pidf = os.path.join(pr["run"], "pid")
        try:
            pid, prog = open(pidf).read().split(None, 1)
            pid, prog = int(pid), prog.strip()
        except (OSError, ValueError):
            print(f"{pr['element']}/{pr['process']}: not running (no pid file)")
            continue
        try:
            exe = os.readlink(f"/proc/{pid}/exe")
        except OSError:
            exe = None
        if exe is None or os.path.realpath(exe) != os.path.realpath(prog):
            print(f"{pr['element']}/{pr['process']}: pid {pid} {'is gone' if exe is None else 'is ' + exe}; "
                  "nothing to stop")
            os.remove(pidf)
            continue
        os.kill(pid, SIGNALS[pr["stop"]])
        end = time.monotonic() + 15
        while time.monotonic() < end and os.path.exists(f"/proc/{pid}") and \
                open(f"/proc/{pid}/stat").read().rsplit(")", 1)[1].split()[0] != "Z":
            time.sleep(0.1)
        if os.path.exists(f"/proc/{pid}") and open(f"/proc/{pid}/stat").read().rsplit(")", 1)[1].split()[0] != "Z":
            os.kill(pid, signal.SIGKILL)
            print(f"{pr['element']}/{pr['process']}: pid {pid} did not stop on {pr['stop']} within 15 s: SIGKILL")
            rc = 1
        else:
            print(f"{pr['element']}/{pr['process']}: pid {pid} stopped ({pr['stop']})")
        os.remove(pidf)
    if not args.processes_only and shutil.which("tmux"):
        subprocess.run(["tmux", "-L", SESSION_SOCKET, "kill-session", "-t", f"{SESSION_SOCKET}-{args.node}"],
                       capture_output=True)
    return rc


