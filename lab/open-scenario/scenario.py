def vty_cmds(host, port, cmds, timeout=4.0):
    try:
        s = socket.create_connection((host, port), timeout=timeout)
    except OSError:
        return None
    s.settimeout(timeout)

    def until_prompt():
        buf, end = b"", time.monotonic() + timeout
        while time.monotonic() < end:
            try:
                c = s.recv(65536)
            except socket.timeout:
                break
            if not c:
                break
            buf += c
            if re.search(rb"[>#] $", buf):
                break
        return buf
    out = until_prompt()
    for c in ["enable"] + list(cmds):
        s.sendall(c.encode() + b"\r\n")
        out += until_prompt()
    s.close()
    return out.decode("latin-1")


def native(m, res):
    """Start every process alone with its generated config in a scratch directory, check that it parsed it (VTY
    answers 'show running-config' / the process stays up), stop it. Needs the node addresses and free ports."""
    ok = True
    kept = {}           # virtphy processes stay up while their mobile is checked (its L1CTL socket)

    def stop(p, sig):
        if p.poll() is None:
            try:
                os.killpg(p.pid, sig)
                p.wait(timeout=10)
            except subprocess.TimeoutExpired:
                os.killpg(p.pid, signal.SIGKILL)
                p.wait()
            except OSError:
                pass
    for eid, e in m["el"].items():
        for pr in processes(m, eid):
            tmp = tempfile.mkdtemp(prefix=f"open-scenario-{pr['process']}-")
            env = dict(os.environ, **{k: v for k, v in pr["env"].items()})
            if "HOME" in pr["env"]:
                os.makedirs(os.path.join(pr["env"]["HOME"], ".osmocom", "bb"), exist_ok=True)
            os.makedirs(pr["run"], mode=0o700, exist_ok=True)
            os.chmod(pr["run"], 0o700)
            if pr["copy_cfg"]:
                shutil.copyfile(pr["copy_cfg"], os.path.join(pr["run"], os.path.basename(pr["copy_cfg"])))
            log = open(os.path.join(tmp, "out.log"), "wb")
            p = subprocess.Popen([pr["program"]] + pr["args"], cwd=pr["run"], stdout=log, stderr=subprocess.STDOUT,
                                 stdin=subprocess.DEVNULL, env=env, start_new_session=True)
            detail, good = "", False
            end = time.monotonic() + 8
            while time.monotonic() < end and p.poll() is None:
                if e.get("vty") and pr["process"] != "bsc-aworker":
                    out = vty_cmds(addr(m, eid), e["vty"], ["show running-config"], 2)
                    if out and "Current configuration" in out:
                        good, detail = True, "VTY answers, running-config shown"
                        break
                elif pr["process"] == "bsc-aworker":
                    if os.path.exists(supervisor_socket(m, eid)):
                        good, detail = True, "pool started, session socket listening"
                        break
                elif time.monotonic() > end - 6:
                    good, detail = True, "running"
                    break
                time.sleep(0.2)
            rc = p.poll()
            if rc is not None:
                good = False
                tail = open(os.path.join(tmp, "out.log"), errors="replace").read()[-300:].replace("\n", " | ")
                detail = f"exited {rc}: {tail}"
            if e["type"] == "virtphy" and good:
                kept[eid] = p
            else:
                stop(p, SIGNALS[pr["stop"]])
            if e["type"] == "mobile":
                stop(kept.pop(e["virtphy"], subprocess.Popen(["true"])), signal.SIGTERM)
            ok = res(good, f"{eid}/{pr['process']}: {detail}" + (" (with its virtphy)" if e["type"] == "mobile" else ""))\
                and ok
            shutil.rmtree(tmp, ignore_errors=True)
    for p in kept.values():
        stop(p, signal.SIGTERM)
    return ok


def c_wait_for(args):
    end = time.monotonic() + args.timeout
    first = True
    while time.monotonic() < end:
        try:
            if args.kind == "unix":
                try:            # the Supervisor's session socket is SOCK_SEQPACKET; others are streams
                    s = socket.socket(socket.AF_UNIX, socket.SOCK_SEQPACKET)
                    s.settimeout(1)
                    s.connect(args.target)
                except OSError as x:
                    if x.errno != 91:       # EPROTOTYPE: not a seqpacket socket
                        raise
                    s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
                    s.settimeout(1)
                    s.connect(args.target)
            else:
                host, port = args.target.rsplit(":", 1)
                s = socket.socket(socket.AF_INET, socket.SOCK_STREAM,
                                  socket.IPPROTO_SCTP if args.kind == "sctp" else 0)
                s.settimeout(1)
                s.connect((host, int(port)))
            s.close()
            return 0
        except OSError:
            if first:
                print(f"waiting for {args.kind} {args.target} ...", flush=True)
                first = False
            time.sleep(0.5)
    print(f"gave up waiting for {args.kind} {args.target} after {args.timeout} s")
    return 1


