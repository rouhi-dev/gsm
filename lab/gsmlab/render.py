"""Render one Osmocom configuration per instance from the lab model.

The topology is authoritative: addresses, ports, point codes, PLMN, cell identities and the remote end
of every link are filled in from the model, never guessed. Anything not modelled goes into
`instances.<id>.raw`, which is appended verbatim (VTY syntax, starting at the top-level node).

Each instance runs in its own directory <node.run_dir>/<instance>, so relative state files (hlr.db,
sms.db, unix sockets) never collide between instances on one node.

The VTY commands used here are those of the pinned release set; most are taken from the CI-proven smoke
configs in tests/smoke/.
"""

from dataclasses import dataclass, field

from .services import SERVICES
from .topology import ss7_domains

HEADER = "! GENERATED by gsm-lab for instance '{id}' ({service}) of lab '{lab}'. Do not edit:\n" \
         "! change the lab description or instances.{id}.raw, then `gsm-lab render`.\n"


@dataclass
class Launch:
    instance: str
    node: str
    workdir: str
    argv: list
    env: dict
    config: str | None            # rendered configuration text (None: binary takes no config file)
    config_path: str | None
    files: dict = field(default_factory=dict)   # extra files to place in workdir: name -> text
    dirs: list = field(default_factory=list)    # extra directories to create below workdir


def _log(level):
    return ("log stderr\n logging filter all 1\n logging color 0\n logging print category 1\n"
            " logging print category-hex 0\n logging timestamp 1\n logging print extended-timestamp 1\n"
            f" logging level set-all {level}\n")


def _vty(ep):
    return f"line vty\n no login\n bind {ep.ip} {ep.port}\n"


def _ctrl(ep):
    return f"ctrl\n bind {ep.ip} {ep.port}\n" if ep else ""


def _plmn_lines(pl, indent=" "):
    return f"{indent}network country code {pl.mcc}\n{indent}mobile network code {pl.mnc}\n"


def _rctx(lab, stp_id, iid):
    """Deterministic M3UA routing context per ASP inside one STP domain (1-based, declaration order)."""
    members = [m for m, _ in ss7_domains(lab).get(stp_id, [])]
    return members.index(iid) + 1


def _ss7_client(lab, i, net):
    stp = lab.instances[net.stp]
    ep = stp.ports["m3ua"]
    transport = stp.opts.get("transport", "tcp")
    local_port = i.opts.get("m3ua_local_port", 0) if net.routing == "static" else 0
    s = (f"cs7 instance 0\n point-code {i.opts['point_code']}\n"
         f" asp asp-{i.id} {ep.port} {local_port} m3ua {transport}\n"
         f"  remote-ip {ep.ip}\n  local-ip {i.bind}\n  role asp\n  transport-role client\n")
    if net.routing == "static":
        s += (f" as as-{i.id} m3ua\n  asp asp-{i.id}\n"
              f"  routing-key {_rctx(lab, net.stp, i.id)} {i.opts['point_code']}\n")
    return s


def _mgcp_client(lab, i, mgw_id, local_port):
    m = lab.instances[mgw_id].ports["mgcp"]
    return (f" mgw 0\n  remote-ip {m.ip}\n  remote-port {m.port}\n  local-ip {i.bind}\n"
            f"  local-port {local_port}\n  keepalive request-interval 2\n  keepalive timeout 6\n")


# ---------------------------------------------------------------- per service
def r_stp(lab, i):
    ep = i.ports["m3ua"]
    transport = i.opts.get("transport", "tcp")
    nets = [n for n in lab.networks.values() if n.stp == i.id]
    static = any(n.routing == "static" for n in nets)
    s = "cs7 instance 0\n"
    if i.opts.get("point_code") is not None:
        s += f" point-code {i.opts['point_code']}\n"
    if not static:
        s += " xua rkm routing-key-allocation dynamic-permitted\n"
    s += f" listen m3ua {ep.port} {transport}\n  local-ip {ep.ip}\n"
    if not static:
        s += "  accept-asp-connections dynamic-permitted\n"
    if static:
        routes = ""
        for iid, _ in ss7_domains(lab).get(i.id, []):
            c = lab.instances.get(iid)
            if not c:
                continue
            s += (f" asp asp-{iid} {c.opts.get('m3ua_local_port', 0)} {ep.port} m3ua {transport}\n"
                  f"  remote-ip {c.bind}\n  local-ip {ep.ip}\n  role sg\n  transport-role server\n"
                  f" as as-{iid} m3ua\n  asp asp-{iid}\n  routing-key {_rctx(lab, i.id, iid)} {c.opts['point_code']}\n")
            routes += f"  update route {c.opts['point_code']} 7.255.7 linkset as-{iid}\n"
        s += " route-table system\n" + routes
    return s


def r_hlr(lab, i):
    s = f"hlr\n gsup\n  bind ip {i.ports['gsup'].ip}\n ussd route prefix *#100# internal own-msisdn\n"
    return s


def r_mgw(lab, i):
    m = i.ports["mgcp"]
    lo, hi = (i.opts.get("rtp_range") or [4002, 16001])[:2]
    return (f"mgcp\n bind ip {m.ip}\n bind port {m.port}\n rtp port-range {lo} {hi}\n"
            f" rtp bind-ip {i.opts.get('rtp_bind', m.ip)}\n number endpoints {i.opts.get('endpoints', 31)}\n"
            " domain mgw\n")


def r_msc(lab, i):
    net = next(n for n in lab.networks.values() if n.msc == i.id)
    pl = lab.plmns[net.plmn]
    hlr = lab.instances[net.hlr].ports["gsup"]
    sgs = i.ports["sgs"]
    return ("network\n" + _plmn_lines(pl) +
            f" short name {net.short_name}\n long name {net.long_name}\n encryption {net.encryption}\n"
            f" authentication {net.authentication}\n" +
            _mgcp_client(lab, i, net.mgw, i.ports["mgcp_client"].port) +
            _ss7_client(lab, i, net) +
            "msc\n cs7-instance-a 0\n mncc internal\n assign-tmsi\n"
            f"hlr\n remote-ip {hlr.ip}\n remote-port {hlr.port}\n"
            f"sgs\n local-ip {sgs.ip}\n local-port {sgs.port}\n")


def r_bsc(lab, i):
    net, link = next((n, b) for n in lab.networks.values() for b in n.bscs if b.id == i.id)
    msc = lab.instances[net.msc]
    ran = lab.plmns[link.ran_plmn or net.plmn]
    s = f"e1_input\n e1_line 0 driver ipa\n ipa bind {i.ports['abis_oml'].ip}\n"
    s += _ss7_client(lab, i, net)
    s += f" sccp-address msc-{msc.id}\n  routing-indicator PC\n  point-code {msc.opts['point_code']}\n"
    s += "network\n" + _plmn_lines(ran) + f" encryption {net.encryption}\n"
    s += _mgcp_client(lab, i, link.mgw, i.ports["mgcp_client"].port)
    for c in link.cells:
        s += (f" bts {c.number}\n  type osmo-bts\n  band {c.band}\n  location_area_code {c.lac}\n"
              f"  cell_identity {c.ci}\n  base_station_id_code {c.bsic}\n  ipa unit-id {c.unit_id} 0\n"
              "  oml ipa stream-id 255 line 0\n  gprs mode none\n")
        for t in c.trx:
            s += (f"  trx {t.index}\n   rf_locked 0\n   arfcn {t.arfcn}\n   nominal power {t.nominal_power}\n"
                  f"   max_power_red {t.max_power_red}\n   rsl e1 tei {t.index}\n")
            for ts, pchan in enumerate(t.timeslots):
                s += f"   timeslot {ts}\n    phys_chan_config {pchan}\n"
    s += f"msc 0\n msc-addr msc-{msc.id}\n allow-emergency deny\n"
    if link.ran_plmn and link.ran_plmn != net.plmn:
        core = lab.plmns[net.plmn]
        s += f" core-mobile-country-code {core.mcc}\n core-mobile-network-code {core.mnc}\n"
    return s


def r_bts(lab, i, workdir):
    found = lab.cell(i.id)
    _, link, cell = found
    bsc = lab.instances[link.id]
    s = "e1_input\n e1_line 0 driver ipa\n e1_line 0 port 0\n no e1_line 0 keepalive\n"
    s += "phy 0\n"
    if i.variant == "virtual":
        vu = i.opts["virtual_um"]
        s += (f" virtual-um ms-multicast-group {vu['ms_group']}\n virtual-um ms-udp-port {vu['ms_port']}\n"
              f" virtual-um bts-multicast-group {vu['bts_group']}\n virtual-um bts-udp-port {vu['bts_port']}\n")
        if vu.get("netdev"):
            s += f" virtual-um net-device {vu['netdev']}\n"
        if vu.get("ttl") is not None:
            s += f" virtual-um ttl {vu['ttl']}\n"
        chans = [t.index for t in cell.trx]
    else:
        phy = lab.instances[cell.trx[0].phy]
        o = i.opts.get("trx_options") or {}
        s += (f" osmotrx ip local {i.bind}\n osmotrx ip remote {phy.ports['trxd'].ip}\n"
              f" osmotrx base-port local {o.get('local_base_port', 5800)}\n"
              f" osmotrx base-port remote {phy.ports['trxd'].port}\n")
        chans = [t.channel for t in cell.trx]
    for ch in sorted(chans):
        s += f" instance {ch}\n"
    s += (f"bts 0\n band {cell.band}\n ipa unit-id {cell.unit_id} 0\n oml remote-ip {bsc.ports['abis_oml'].ip}\n"
          f" pcu-socket {workdir}/pcu_bts\n")
    for t, ch in zip(cell.trx, chans):
        s += f" trx {t.index}\n  phy 0 instance {ch}\n"
    return s


def r_trx(lab, i):
    users = [(c, t) for _, _, c in lab.cells() for t in c.trx if t.phy == i.id]
    bts = lab.instances[users[0][0].id] if users else None
    o = dict(i.opts.get("trx_options") or {})
    s = (f"trx\n bind-ip {i.ports['trxd'].ip}\n remote-ip {bts.bind if bts else '127.0.0.1'}\n"
         f" base-port {i.ports['trxd'].port}\n")
    if i.opts.get("dev_args"):
        s += f" dev-args {i.opts['dev_args']}\n"
    for k, v in {"tx-sps": 4, "rx-sps": 4, "clock-ref": "internal", "egprs": "disable", **o}.items():
        if k in ("local_base_port",):
            continue
        s += f" {k} {v}\n"
    for ch in sorted({t.channel for _, t in users}) or [0]:
        s += f" chan {ch}\n"
    return s


def r_mobile(lab, i, workdir):
    s = ""
    for n, sim in enumerate(i.opts.get("sims") or [], start=1):
        vp = sim.get("virtphy", i.opts.get("virtphy"))
        ki = str(sim.get("ki", "")).lower()
        ki_sp = " ".join(ki[k:k + 2] for k in range(0, len(ki), 2))
        sock = f"{lab.nodes[i.node].run_dir}/{vp}/l1ctl"
        s += (f"ms {n}\n layer2-socket {sock}\n sap-socket {workdir}/sap-{n}\n mncc-socket {workdir}/mncc-{n}\n"
              " mncc-handler internal\n sim test\n network-selection-mode auto\n"
              f" imei {sim.get('imei', '00000000000000' + str(n % 10))} 0\n imei-fixed\n"
              " sms-service-center 12345\n location-updating\n test-sim\n"
              f"  imsi {sim['imsi']}\n" + (f"  ki comp128 {ki_sp}\n" if ki else "") +
              "  no barred-access\n no shutdown\n")
    return s


# ---------------------------------------------------------------- entry points
def render(lab, iid):
    i = lab.instances[iid]
    node = lab.nodes[i.node]
    svc = SERVICES[i.service]
    workdir = lab.instance_dir(i)
    binary = svc.variants.get(i.variant, svc.binary) if svc.variants else svc.binary
    exe = f"{node.prefix}/bin/{binary}"
    env = {"LD_LIBRARY_PATH": f"{node.prefix}/lib"}

    if i.service == "virtphy":
        vu = i.opts["virtual_um"]
        argv = [exe, "-s", f"{workdir}/l1ctl", "-z", vu["ms_group"], "-y", vu["bts_group"], "-x", str(vu["ms_port"])]
        if vu.get("netdev"):
            argv += ["-D", vu["netdev"]]
        return Launch(iid, i.node, workdir, argv + i.args, env, None, None)

    cfg_path = f"{workdir}/{i.id}.cfg"
    if i.config_file:
        return Launch(iid, i.node, workdir, [exe, "-c", i.config_file] + i.args, env, None, None)

    body = {
        "stp": lambda: r_stp(lab, i), "hlr": lambda: r_hlr(lab, i), "mgw": lambda: r_mgw(lab, i),
        "msc": lambda: r_msc(lab, i), "bsc": lambda: r_bsc(lab, i), "bts": lambda: r_bts(lab, i, workdir),
        "trx": lambda: r_trx(lab, i), "mobile": lambda: r_mobile(lab, i, workdir),
    }[i.service]()
    text = (HEADER.format(id=i.id, service=i.service, lab=lab.name) + _log(i.log_level) + _vty(i.vty)
            + _ctrl(i.ctrl) + body)
    if i.raw:
        text += "! ---- instances." + i.id + ".raw\n" + i.raw.rstrip("\n") + "\n"
    flag = "-C" if i.service == "trx" else "-c"
    argv = [exe, flag, cfg_path]
    dirs = []
    if i.service == "mobile":
        env["HOME"] = workdir          # mobile keeps sms.txt / state below $HOME/.osmocom/bb ...
        dirs.append(".osmocom/bb")     # ... and rejects MT SMS ('Memory Exceeded') if it does not exist
    if i.service == "hlr" and i.opts.get("db"):
        argv += ["-l", i.opts["db"]]
    return Launch(iid, i.node, workdir, argv + i.args, env, text, cfg_path, dirs=dirs)


def render_all(lab):
    return {iid: render(lab, iid) for iid, i in lab.instances.items() if i.node in lab.nodes}


def hlr_subscribers(lab):
    """HLR instance -> list of {imsi, msisdn, ki} to provision: explicit `subscribers:` plus every SIM of
    every mobile, assigned to the HLR of the network whose PLMN matches the IMSI prefix."""
    out = {iid: list(i.opts.get("subscribers") or []) for iid, i in lab.instances.items() if i.service == "hlr"}
    for i in lab.instances.values():
        if i.service != "mobile":
            continue
        for sim in i.opts.get("sims") or []:
            imsi = str(sim.get("imsi", ""))
            for n in lab.networks.values():
                pl = lab.plmns.get(n.plmn)
                if pl and n.hlr in out and imsi.startswith(pl.mcc + pl.mnc):
                    if not any(str(s.get("imsi")) == imsi for s in out[n.hlr]):
                        out[n.hlr].append({"imsi": imsi, "msisdn": sim.get("msisdn"), "ki": sim.get("ki")})
                    break
    return out
