def elf_dynamic(path):
    """(soname, [needed]) of an ELF file, or None if it is no ELF / has no dynamic section."""
    try:
        with open(path, "rb") as f:
            ident = f.read(16)
            if len(ident) < 16 or ident[:4] != b"\x7fELF":
                return None
            is64 = ident[4] == 2
            end = "<" if ident[5] == 1 else ">"
            f.seek(0)
            hdr = f.read(64 if is64 else 52)
            if is64:
                shoff, = struct.unpack(end + "Q", hdr[0x28:0x30])
                shentsize, shnum, shstrndx = struct.unpack(end + "HHH", hdr[0x3A:0x40])
            else:
                shoff, = struct.unpack(end + "I", hdr[0x20:0x24])
                shentsize, shnum, shstrndx = struct.unpack(end + "HHH", hdr[0x2E:0x34])
            if not shoff or not shnum or shnum > 4096:
                return None
            secs = []
            for i in range(shnum):
                f.seek(shoff + i * shentsize)
                sh = f.read(shentsize)
                if is64:
                    _, typ, _, _, off, size, link, _, _, entsize = struct.unpack(end + "IIQQQQIIQQ", sh[:64])
                else:
                    _, typ, _, _, off, size, link, _, _, entsize = struct.unpack(end + "IIIIIIIIII", sh[:40])
                secs.append((typ, off, size, link, entsize))
            dyn = [s for s in secs if s[0] == 6]          # SHT_DYNAMIC
            if not dyn:
                return ("", [])
            typ, off, size, link, entsize = dyn[0]
            if link >= len(secs) or size > 1 << 20:
                return None
            _, soff, ssize, _, _ = secs[link]
            f.seek(soff)
            strtab = f.read(min(ssize, 1 << 22))
            f.seek(off)
            data = f.read(size)
            fmt, step = (end + "qQ", 16) if is64 else (end + "iI", 8)

            def s(o):
                return strtab[o:strtab.index(b"\0", o)].decode("latin-1") if o < len(strtab) else ""
            soname, needed = "", []
            for i in range(0, len(data) - step + 1, step):
                tag, val = struct.unpack(fmt, data[i:i + step])
                if tag == 0:
                    break
                if tag == 1:
                    needed.append(s(val))
                elif tag == 14:
                    soname = s(val)
            return (soname, needed)
    except (OSError, struct.error, ValueError):
        return None


def is_gsm_lib_name(name):
    """libosmocore, libosmocore.so.22, libosmo-gprs-llc.a, ...: a library of the GSM stack (GSM_LIBS)."""
    base = re.sub(r"(\.so(\.\d+)*|\.la|\.a)$", "", name)
    return any(base == p or base.startswith(p + "-") for p in GSM_LIBS)


def links_gsm_lib(dyn):
    return bool(dyn) and any(is_gsm_lib_name(n) for n in dyn[1])


# ------------------------------------------------------------------ git helpers

def git(args, cwd=None, gitdir=None):
    cmd = ["git"]
    if gitdir:
        cmd += ["--git-dir", gitdir]
    r = subprocess.run(cmd + args, cwd=cwd, capture_output=True, text=True,
                       env={**os.environ, "GIT_TERMINAL_PROMPT": "0", "GIT_OPTIONAL_LOCKS": "0"})
    return r.returncode, r.stdout


def git_dirs(top):
    """(gitdir, commondir, is_linked_worktree) of a working tree whose .git is at top/.git, or None."""
    dotgit = os.path.join(top, ".git")
    if os.path.isdir(dotgit) and not os.path.islink(dotgit):
        return dotgit, dotgit, False
    if os.path.isfile(dotgit):
        try:
            line = read_text(dotgit, 4096).strip()
        except OSError:
            return None
        if not line.startswith("gitdir:"):
            return None
        gd = norm(os.path.join(top, line[7:].strip()))
        cd = gd
        cf = os.path.join(gd, "commondir")
        if os.path.isfile(cf):
            cd = norm(os.path.join(gd, read_text(cf, 4096).strip()))
        return gd, cd, os.path.isfile(cf) and "/worktrees/" in gd
    return None


def remotes(commondir):
    rc, out = git(["config", "--get-regexp", r"^remote\..*\.url$"], gitdir=commondir)
    return [l.split(None, 1)[1] for l in out.splitlines() if " " in l] if rc == 0 else []


def backup_refs(gitdir):
    """Refs under refs/backup/ in a git directory and in every git directory below it (submodules)."""
    found = []
    for root, dirs, files in os.walk(gitdir):
        rel = os.path.relpath(root, gitdir)
        if os.path.basename(root) == "objects":
            dirs[:] = []
            continue
        if "/refs/backup" in "/" + rel or rel.startswith("refs/backup"):
            found += [os.path.join(root, f) for f in files]
        if "packed-refs" in files:
            try:
                for line in read_text(os.path.join(root, "packed-refs"), None).splitlines():
                    if (" " + BACKUP_REF_PREFIX) in line:
                        found.append(os.path.join(root, "packed-refs") + ": " + line.split()[-1])
            except OSError:
                pass
    return found


