def apply(items, log=print):
    """Remove the 'remove' items: files and links first, then directories deepest first; namespace directories only
    when empty. Re-checks each item's lstat signature; returns (removed, skipped) lists of (item, why)."""
    removed, skipped = [], []
    todo = [i for i in items if i.action == "remove" and not i.extra.get("with_parent")]
    order = {"file": 0, "link": 0, "dir": 1, "worktree": 2, "repo": 3}
    todo.sort(key=lambda i: (order.get(i.kind, 1), -i.path.count("/")))
    gone = []
    for i in todo:
        if any(under(i.path, g) for g in gone):
            removed.append((i, "removed with its parent"))
            continue
        try:
            sig = lsig(i.path)
        except OSError:
            skipped.append((i, "already gone"))
            continue
        if i.extra.get("only_if_empty"):
            # empty subdirectories first (bottom-up); a directory holding any file or link is never removed
            try:
                for d, dirs, files in os.walk(i.path, topdown=False, followlinks=False):
                    if d != i.path and not os.listdir(d):
                        os.rmdir(d)
                if os.listdir(i.path):
                    skipped.append((i, "not empty (other files remain)"))
                    continue
                os.rmdir(i.path)
                removed.append((i, "empty directory removed"))
                gone.append(i.path)
            except OSError as e:
                skipped.append((i, e.strerror or str(e)))
            continue
        same = tuple(sig[:3]) == tuple(i.sig[:3]) if stat.S_ISDIR(sig[0]) else tuple(sig) == tuple(i.sig)
        if not same:
            skipped.append((i, "changed since the scan"))
            continue
        try:
            if stat.S_ISDIR(sig[0]):
                shutil.rmtree(i.path)
                if i.kind == "worktree" and i.extra.get("commondir"):
                    git(["worktree", "prune"], gitdir=i.extra["commondir"])
            else:
                os.unlink(i.path)
            removed.append((i, "removed"))
            gone.append(i.path)
            log(f"  removed {i.path}")
        except PermissionError:
            skipped.append((i, "permission denied (needs root: rerun with sudo)"))
        except OSError as e:
            skipped.append((i, e.strerror or str(e)))
    return removed, skipped


# ------------------------------------------------------------------ report

def report(items, notes=(), verbose=False):
    lines = []
    for action, title in (("remove", "WILL REMOVE"), ("preserve", "PRESERVED (ownership not established or "
                                                                   "unsafe)"), ("protected", "PROTECTED")):
        sel = [i for i in items if i.action == action]
        lines.append(f"== {title}: {len(sel)}")
        for cat in ("repo", "prefix", "install", "build", "repo-build", "state", "temp"):
            cs = sorted((i for i in sel if i.category == cat), key=lambda i: i.path)
            if not cs:
                continue
            lines.append(f"  [{cat}]")
            for i in cs:
                lines.append(f"    {i.path}  -- {i.reason}")
                if verbose and i.evidence:
                    lines.append(f"        evidence: {'; '.join(i.evidence)}")
    for n in notes:
        lines.append(f"note: {n}")
    return "\n".join(lines)


def default_home():
    if os.geteuid() == 0 and os.environ.get("SUDO_USER"):
        return pwd.getpwnam(os.environ["SUDO_USER"]).pw_dir
    return os.path.expanduser("~")


def default_uid():
    if os.geteuid() == 0 and os.environ.get("SUDO_UID"):
        return int(os.environ["SUDO_UID"])
    return os.getuid()


def run(args):
    home = norm(args.home or default_home())
    roots = [norm(r) for r in (args.root or [])] or [home] + [d for d in ("/opt", "/usr/local/src", "/usr/src",
                                                                         "/srv") if os.path.isdir(d)]
    sc = Scanner(home=home, roots=roots, prefixes=args.prefix, with_repo=args.repo,
                 discard_local_work=args.discard_local_work, keep_repo_builds=args.keep_repo_builds,
                 default_prefixes=not args.no_default_prefixes, uid=default_uid())
    t0 = time.monotonic()
    items = sc.scan()
    print(f"gsm-lab cleanup: scanned {', '.join(roots)} and {len(sc.prefixes())} prefix(es) in "
          f"{time.monotonic() - t0:.1f} s; {sum(1 for r in sc.repos.values() if r['verified'])} GSM/Osmocom "
          f"repositor(ies), {len(sc.build_trees)} build tree(s)")
    print(report(items, sc.notes, verbose=args.verbose))
    if args.json:
        with open(args.json, "w") as f:
            json.dump({"home": home, "roots": roots, "prefixes": sc.prefixes(), "repo": args.repo,
                       "items": [i.to_json() for i in items], "notes": sc.notes}, f, indent=1)
    todo = [i for i in items if i.action == "remove"]
    if not args.apply:
        print(f"\nDry run: nothing changed. {len(todo)} item(s) would be removed; run again with --apply.")
        return 0
    if not todo:
        print("\nNothing to remove.")
        return 0
    if not args.yes:
        try:
            ans = input(f"\nRemove these {len(todo)} item(s)? Type 'remove' to continue: ")
        except EOFError:
            ans = ""
        if ans.strip() != "remove":
            print("Aborted: nothing changed.")
            return 1
    removed, skipped = apply(items)
    print(f"\nRemoved {len(removed)} item(s); skipped {len(skipped)}:")
    for i, why in skipped:
        print(f"  skipped {i.path}: {why}")
    if any("/lib" in i.path and ".so" in i.path for i, _ in removed if i.category == "install"):
        print("Shared libraries were removed from a prefix: run `sudo ldconfig` if that prefix is in the "
              "dynamic linker's search path.")
    return 0 if not skipped else 2
