"""gsm-lab cleanup: find and remove what the GSM/Osmocom projects left on this machine.

Every item is classified with evidence before anything is touched:

  remove     ownership established (evidence listed per item)
  preserve   ownership not established, or removing it would be unsafe (reason listed)
  protected  never removed (history backups, repositories holding backup refs)

Without --apply nothing is changed. With --apply the plan is executed exactly as reported; each item is
re-checked (same type, inode, size, mtime) right before it is removed, and items in use by a running process are
skipped. Symbolic links are removed as links; their targets are never followed.

Categories:
  install      files that `make install` put into a prefix (/usr/local, /opt/<x>, ~/.local, any --prefix)
  prefix       a whole prefix that holds nothing but GSM/Osmocom software (e.g. --prefix=/opt/osmocom)
  build        out-of-tree build directories configured from a GSM/Osmocom source tree
  repo-build   the gsm workspace's own build output (_build/, _install/): git-ignored, regenerated by ./gsm build
  state        gsm-lab runtime state (~/.local/state/gsm-lab) and generated tmuxinator projects
  temp         temporary leftovers of the A-worker tests and snapshots (/tmp, /dev/shm)
  repo         (--repo only) GSM/Osmocom git repositories, linked worktrees and exported source trees
"""

