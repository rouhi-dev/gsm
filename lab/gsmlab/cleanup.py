@dataclass
class Item:
    category: str
    path: str
    action: str                 # remove | preserve | protected
    reason: str
    kind: str = "file"          # file | dir | link | worktree | repo
    evidence: list = field(default_factory=list)
    sig: tuple = ()             # lstat signature at scan time
    extra: dict = field(default_factory=dict)

    def to_json(self):
        d = asdict(self)
        d["sig"] = list(self.sig)
        return d


def lsig(path):
    st = os.lstat(path)
    return (stat.S_IFMT(st.st_mode), st.st_ino, st.st_dev, st.st_size, int(st.st_mtime))


def norm(p):
    return os.path.normpath(os.path.abspath(os.path.expanduser(p)))


def under(path, root):
    path, root = norm(path), norm(root)
    return path == root or path.startswith(root.rstrip("/") + "/")


