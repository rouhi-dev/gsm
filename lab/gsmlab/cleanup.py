class Scanner:
    def __init__(self, home=None, roots=None, prefixes=None, temp_dirs=("/tmp", "/dev/shm"), with_repo=False,
                 discard_local_work=False, keep_repo_builds=False, default_prefixes=True,
                 dpkg_info="/var/lib/dpkg/info", uid=None, protected=()):
        self.home = norm(home or os.path.expanduser("~"))
        self.roots = [norm(r) for r in (roots or [self.home])]
        self.extra_prefixes = [norm(p) for p in (prefixes or [])]
        self.temp_dirs = [norm(t) for t in temp_dirs]
        self.with_repo = with_repo
        self.discard = discard_local_work
        self.keep_repo_builds = keep_repo_builds
        self.default_prefixes = default_prefixes
        self.dpkg_info = dpkg_info
        self.uid = os.getuid() if uid is None else uid
        self.protected = [norm(p.replace("~", self.home, 1)) for p in PROTECTED_GLOBS] + [norm(p) for p in protected]
        self.items = []
        self.repos = {}           # top -> info
        self.source_trees = {}    # path -> name (exported trees, no .git)
        self.build_trees = []     # (dir, srcdir, prefix)
        self.programs, self.scripts, self.libs, self.pcs = set(), set(), set(), set()
        self.headers, self.units, self.cfgs, self.components = set(), set(), set(GSM_COMPONENTS), set()
        self._pkgdb = None
        self.notes = []

    # ---------------- protection / package manager
    def is_protected(self, path):
        """The protected path p is, is inside, or would remove (an ancestor of an existing protected path)."""
        p = norm(path)
        for pat in self.protected:
            if fnmatch.fnmatch(p, pat):
                return pat
            for d in self._glob_dirs(pat):
                if under(p, d) or under(d, p):
                    return d
        return None

    def _glob_dirs(self, pat):
        base = os.path.dirname(pat)
        if not any(c in pat for c in "*?["):
            return [pat] if os.path.exists(pat) else []
        try:
            return [os.path.join(base, n) for n in os.listdir(base) if fnmatch.fnmatch(os.path.join(base, n), pat)]
        except OSError:
            return []

    def pkg_owned(self, path):
        if self._pkgdb is None:
            self._pkgdb = set()
            if self.dpkg_info and os.path.isdir(self.dpkg_info):
                for n in os.listdir(self.dpkg_info):
                    if n.endswith(".list"):
                        try:
                            self._pkgdb.update(read_text(os.path.join(self.dpkg_info, n), None).splitlines())
                        except OSError:
                            pass
        if path in self._pkgdb or os.path.realpath(path) in self._pkgdb:
            return "dpkg"
        if shutil.which("rpm") and os.path.isdir("/var/lib/rpm"):
            r = subprocess.run(["rpm", "-qf", "--quiet", path], capture_output=True)
            if r.returncode == 0:
                return "rpm"
        return None

    def add(self, item):
        try:
            item.sig = lsig(item.path)
        except OSError:
            return
        if item.action == "remove":
            prot = self.is_protected(item.path)
            if prot:
                item.action, item.reason = "protected", f"contains or is protected path {prot}"
            elif norm(item.path) in SYSTEM_DIRS or norm(item.path) in (self.home,) or norm(item.path) in self.roots:
                item.action, item.reason = "preserve", "system, home or scan-root directory: never removed"
            elif item.kind != "repo" and item.kind != "worktree" and self.pkg_owned(item.path):
                item.action, item.reason = "preserve", f"owned by the package manager ({self.pkg_owned(item.path)})"
        self.items.append(item)

    # ---------------- discovery walk
    def walk(self):
        """One pass over the roots: git repositories, exported source trees, out-of-tree build directories."""
        seen = set()
        for root in self.roots:
            if not os.path.isdir(root):
                continue
            for d, dirs, files in os.walk(root, followlinks=False):
                if d in seen:
                    dirs[:] = []
                    continue
                seen.add(d)
                dirs[:] = [x for x in dirs if x not in PRUNE_DIRS and not os.path.islink(os.path.join(d, x))]
                if ".git" in files or os.path.isdir(os.path.join(d, ".git")):
                    self.repo_found(d)
                    dirs[:] = []          # a repository is handled as one unit (submodules included)
                    continue
                if "config.status" in files:
                    self.build_found(d)
                    dirs[:] = []
                    continue
                if "configure.ac" in files and ".tarball-version" in files:
                    name = ac_init_name(os.path.join(d, "configure.ac"))
                    if name and self.known_component(name):
                        self.source_trees[d] = name
                    dirs[:] = []

    def known_component(self, name):
        """A component of the GSM stack. Other Osmocom projects (osmo-fl2k, osmo-tetra, osmo-gmr, ...) are not."""
        return name in self.components or name in GSM_COMPONENTS or is_gsm_lib_name(name)

    def repo_found(self, top):
        g = git_dirs(top)
        if not g:
            return
        gitdir, commondir, linked = g
        urls = remotes(commondir)
        info = {"top": top, "gitdir": gitdir, "commondir": commondir, "linked": linked, "urls": urls,
                "verified": False, "why": "", "gsm_super": False, "name": ""}
        is_super = all(os.path.exists(os.path.join(top, p)) for p in ("gsm", "components.conf", "lab/gsmlab"))
        if is_super:
            info.update(verified=True, gsm_super=True, why="gsm workspace (gsm, components.conf, lab/gsmlab)",
                        name="gsm")
            self.read_components(os.path.join(top, "components.conf"))
        for u in urls:
            host, upath = parse_remote(u)
            name = re.sub(r"\.git$", "", upath.rstrip("/").split("/")[-1])
            if host in OSMOCOM_HOSTS or host.endswith(".osmocom.org") or (
                    host == "github.com" and upath.lower().startswith("osmocom/")):
                info.update(verified=True, why=f"remote {u} is an Osmocom repository", name=info["name"] or name)
                break
            if not host:
                info["local_origin"] = norm(upath)
            if self.known_component(name):
                ac = os.path.join(top, "configure.ac")
                ac_name = ac_init_name(ac) if os.path.isfile(ac) else None
                if ac_name and self.known_component(ac_name) and osmocom_configure(ac):
                    info.update(verified=True, why=f"remote {u}: component '{name}', configure.ac AC_INIT "
                                f"'{ac_name}' with Osmocom macros", name=name)
                    break
                if not info["verified"]:
                    info["why"] = f"remote {u} names '{name}', but the sources do not confirm an Osmocom project"
        if not info["verified"] and not info["why"]:
            info["why"] = "no Osmocom remote and no GSM workspace markers"
        self.repos[top] = info

    def read_components(self, path):
        for line in read_text(path, None).splitlines():
            line = line.strip()
            if line and not line.startswith("#"):
                self.components.add(line.split()[0])

    def build_found(self, d):
        srcdir, prefix = config_status(os.path.join(d, "config.status"))
        if srcdir:
            self.build_trees.append((d, srcdir, prefix))

    # ---------------- knowledge from the verified sources
    def learn(self, src):
        for d, dirs, files in os.walk(src, followlinks=False):
            dirs[:] = [x for x in dirs if x not in (".git", "_build", "_install", ".libs", ".deps", "tests")]
            rel = os.path.relpath(d, src)
            for f in files:
                p = os.path.join(d, f)
                if f == "Makefile.am":
                    self.learn_makefile(p)
                elif f.endswith(".pc.in"):
                    self.pcs.add(f[:-3])
                elif f.endswith(".service") and "systemd" in rel:
                    self.units.add(f)
                elif f.endswith(".cfg") and "examples" in rel:
                    self.cfgs.add(f)
                elif f == "configure.ac":
                    n = ac_init_name(p)
                    if n:
                        self.components.add(n)
            if rel == "include" or rel.startswith("include/"):
                for f in files:
                    if f.endswith((".h", ".h.in")):
                        self.headers.add(os.path.relpath(os.path.join(d, f[:-3] if f.endswith(".h.in") else f),
                                                         os.path.join(src, "include")))

    def learn_makefile(self, path):
        try:
            text = read_text(path).replace("\\\n", " ")
        except OSError:
            return
        for m in re.finditer(r"^\s*([A-Za-z0-9_]+?)_(PROGRAMS|SCRIPTS|LTLIBRARIES|LIBRARIES)\s*\+?=(.*)$", text, re.M):
            where, what, vals = m.group(1), m.group(2), m.group(3)
            if where.startswith(("noinst", "check", "EXTRA")):
                continue
            for v in vals.split():
                if "$" in v or "(" in v:
                    continue
                v = os.path.basename(v)
                if what == "PROGRAMS":
                    self.programs.add(v)
                elif what == "SCRIPTS":
                    self.scripts.add(v)
                else:
                    self.libs.add(re.sub(r"\.(la|a)$", "", v))

    # ---------------- the plan
    def scan(self):
        self.walk()
        verified = [r for r in self.repos.values() if r["verified"]]
        # worktrees: verified when their common repository is verified (by its remotes)
        for r in self.repos.values():
            if not r["verified"] and r["linked"]:
                main = [x for x in self.repos.values() if x["commondir"] == r["commondir"] and x["verified"]]
                if main:
                    r.update(verified=True, why=f"worktree of {main[0]['top']}")
        for r in self.repos.values():
            if not r["verified"] and r.get("local_origin") in self.repos and self.repos[r["local_origin"]]["verified"]:
                r.update(verified=True, why=f"clone of {r['local_origin']}")
        for r in self.repos.values():
            if r["verified"]:
                self.learn(r["top"])
        for d in self.source_trees:
            self.learn(d)
        self.plan_repo_builds()
        self.plan_build_trees()
        self.plan_prefixes()
        self.plan_state()
        self.plan_temp()
        self.plan_repos()
        self.check_dependents()
        self.check_running()
        self.fold_children()
        return self.items

    def fold_children(self):
        """An item inside a directory that is removed as a whole goes with it (never removed separately)."""
        dirs = sorted((i.path for i in self.items if i.action == "remove" and i.kind in ("dir", "repo", "worktree")
                       and not i.extra.get("only_if_empty")), key=len)
        for i in self.items:
            if i.action == "remove" and any(under(i.path, d) and norm(i.path) != norm(d) for d in dirs):
                i.extra["with_parent"] = True

    def verified_source(self, path):
        p = norm(path)
        for top, r in self.repos.items():
            if r["verified"] and under(p, top):
                return top
        for d in self.source_trees:
            if under(p, d):
                return d
        return None

    def in_any_repo(self, path):
        return next((t for t in self.repos if under(path, t)), None)

    def plan_repo_builds(self):
        for top, r in self.repos.items():
            if not r["gsm_super"]:
                continue
            for sub in ("_build", "_install"):
                p = os.path.join(top, sub)
                if not os.path.isdir(p) or os.path.islink(p):
                    continue
                rc, _ = git(["check-ignore", "-q", sub], cwd=top)
                if rc != 0:
                    self.add(Item("repo-build", p, "preserve", "not git-ignored in its repository", kind="dir"))
                elif self.keep_repo_builds:
                    self.add(Item("repo-build", p, "preserve", "--keep-repo-builds", kind="dir"))
                else:
                    self.add(Item("repo-build", p, "remove", f"{sub}/ of gsm workspace {top}: git-ignored output of "
                                  "./gsm build", kind="dir", evidence=[r["why"], f"git check-ignore: {sub}"]))

    def plan_build_trees(self):
        for d, srcdir, prefix in self.build_trees:
            src = self.verified_source(srcdir)
            in_repo = self.in_any_repo(d)
            if in_repo and norm(d) == norm(srcdir):
                self.notes.append(f"in-tree build in {d} (part of its source tree; `make distclean` there)")
                continue
            if not src:
                self.add(Item("build", d, "preserve", f"configured from {srcdir}, which is not a verified "
                              "GSM/Osmocom source tree", kind="dir"))
                continue
            if in_repo and self.repos[in_repo]["gsm_super"]:
                continue        # inside _build/: covered by repo-build
            if in_repo:
                self.add(Item("build", d, "preserve", f"inside repository {in_repo}: kept with the repository",
                              kind="dir"))
                continue
            self.add(Item("build", d, "remove", "out-of-tree build directory", kind="dir",
                          evidence=[f"config.status: srcdir {srcdir}", f"source: {src}", f"prefix {prefix}"]))

    def prefixes(self):
        ps = []
        if self.default_prefixes:
            ps += ["/usr/local", os.path.join(self.home, ".local")]
            try:
                ps += [os.path.join("/opt", n) for n in sorted(os.listdir("/opt"))]
            except OSError:
                pass
        for d, srcdir, prefix in self.build_trees:
            if prefix and self.verified_source(srcdir):
                ps.append(prefix)
        ps += self.extra_prefixes
        out = []
        for p in ps:
            p = norm(p)
            if p in out or not os.path.isdir(p) or os.path.islink(p):
                continue
            if self.in_any_repo(p) or any(under(p, b[0]) for b in self.build_trees if self.verified_source(b[1])):
                continue      # in a repository or a build directory: handled with it
            out.append(p)
        return out

    def plan_prefixes(self):
        for pfx in self.prefixes():
            self.plan_prefix(pfx)

    def plan_prefix(self, pfx):
        found, owned_core = [], False
        for sub in ("bin", "sbin", "lib", "lib64", "libexec", "include/osmocom", "etc/osmocom", "share/osmocom",
                    "share/doc", "lib/systemd/system", "lib/pkgconfig"):
            base = os.path.join(pfx, sub)
            if not os.path.isdir(base):
                continue
            for path in list_files(base, None if sub in NAMESPACE_DIRS or sub == "share/doc" else 1):
                found.append(path)
        items = []
        for path in found:
            rel = os.path.relpath(path, pfx)
            res = self.classify_installed(pfx, rel, path)
            if res:
                action, reason, kind, evidence, extra = (res + ({},))[:5]
                items.append(Item("install", path, action, reason, kind=kind, evidence=evidence, extra=extra))
        owned = [i for i in items if i.action == "remove"]
        owned_core = any(i.extra.get("core") for i in owned)
        # namespace files only count when the prefix holds the GSM stack
        for i in items:
            if i.action == "remove" and i.extra.get("needs_core") and not owned_core:
                i.action, i.reason = "preserve", "Osmocom namespace, but no GSM/Osmocom program or library " \
                                                  "confirmed in this prefix"
        # a prefix holding nothing but owned items is removed as a whole (a dedicated prefix)
        if self.dedicated_prefix(pfx, items):
            self.add(Item("prefix", pfx, "remove", "dedicated prefix: everything in it is GSM/Osmocom software",
                          kind="dir", evidence=[f"{len(owned)} owned files, nothing else"]))
            return
        for i in items:
            self.add(i)
        for ns in NAMESPACE_DIRS:
            d = os.path.join(pfx, ns)
            if os.path.isdir(d) and not os.path.islink(d):
                self.add(Item("install", d, "remove" if owned_core else "preserve",
                              "Osmocom namespace directory (removed once empty)" if owned_core else
                              "no GSM/Osmocom program or library confirmed in this prefix", kind="dir",
                              extra={"only_if_empty": True}))
        docs = os.path.join(pfx, "share/doc")
        if os.path.isdir(docs):
            for n in os.listdir(docs):
                d = os.path.join(docs, n)
                if os.path.isdir(d) and not os.path.islink(d) and n in self.components and owned_core:
                    self.add(Item("install", d, "remove", "documentation directory of a GSM component (removed once "
                                  "empty)", kind="dir", extra={"only_if_empty": True}))

    def dedicated_prefix(self, pfx, items):
        if pfx in SYSTEM_DIRS or pfx in ("/usr/local", os.path.join(self.home, ".local")) or under(self.home, pfx):
            return False
        if not any(norm(b[2] or "") == pfx and self.verified_source(b[1]) for b in self.build_trees) and \
                pfx not in self.extra_prefixes and not under(pfx, "/opt"):
            return False
        if not items or any(i.action != "remove" for i in items):
            return False
        owned = {i.path for i in items}
        for path in list_files(pfx, None):
            if path not in owned and not path.endswith(".pyc"):
                return False
        return True

    def classify_installed(self, pfx, rel, path):
        """(action, reason, kind, evidence) for a file in a prefix, or None to ignore it."""
        name = os.path.basename(path)
        top = rel.split("/")[0]
        islink = os.path.islink(path)
        kind = "link" if islink else "file"
        real = os.path.realpath(path)
        if islink and not os.path.exists(real):
            if is_gsm_lib_name(name) or name.startswith("osmo-") or name in self.programs:
                return ("remove", "dangling symbolic link with a GSM/Osmocom name", kind, [f"-> {os.readlink(path)}"])
            return None
        if top in ("bin", "sbin", "libexec"):
            dyn = elf_dynamic(real)
            known = name in self.programs or name in self.scripts or name.startswith("osmo-")
            if dyn is not None:
                if not links_gsm_lib(dyn):
                    return ("preserve", "ELF program that does not link a GSM/Osmocom library", kind, []) \
                        if known else None
                if known:
                    return ("remove", "GSM/Osmocom program", kind,
                            [f"ELF links {', '.join(n for n in dyn[1] if is_gsm_lib_name(n))}",
                             "name from the project sources" if name in self.programs else "osmo-* program name"],
                            {"core": True})
                return ("preserve", "links a GSM/Osmocom library, but the name is not one the projects install",
                        kind, [])
            if name in self.scripts or name.startswith("osmo-"):
                txt = head(real, 4096)
                if "osmo" in txt.lower():
                    return ("remove", "GSM/Osmocom script", kind, ["script named by the project sources" if name in
                                                               self.scripts else "osmo-* script mentioning osmo"],
                        {"needs_core": True})
                return ("preserve", "script with a GSM/Osmocom name, but its content does not confirm it", kind, [])
            return None
        if top in ("lib", "lib64") and "/" not in rel[len(top) + 1:]:
            base = re.sub(r"(\.so.*|\.la|\.a)$", "", name)
            if not (is_gsm_lib_name(base) or base in self.libs):
                return None
            if ".so" in name:
                dyn = elf_dynamic(real)
                if dyn and (is_gsm_lib_name(dyn[0]) or dyn[0].split(".so")[0] in self.libs):
                    return ("remove", "GSM/Osmocom shared library", kind, [f"ELF SONAME {dyn[0]}"], {"core": True})
                return ("preserve", "library name matches, but the file's SONAME does not", kind, [])
            if name.endswith(".la"):
                txt = head(real, 4096)
                if "libtool library file" in txt and re.search(r"dlname='(libosmo|%s)" % re.escape(base), txt):
                    return ("remove", "libtool archive of a GSM/Osmocom library", kind, ["libtool .la, dlname"],
                            {"core": True})
                return ("preserve", "not a libtool archive of this library", kind, [])
            if name.endswith(".a"):
                if head(real, 8, binary=True) == "!<arch>\n" and (is_gsm_lib_name(base) or base in self.libs):
                    return ("remove", "static GSM/Osmocom library", kind, ["ar archive, library name"])
                return ("preserve", "not an ar archive", kind, [])
            return None
        if rel.startswith(("lib/pkgconfig/", "lib64/pkgconfig/")):
            n = name[:-3] if name.endswith(".pc") else name
            if not name.endswith(".pc"):
                return None
            txt = head(real, 8192)
            if (n in self.pcs or is_gsm_lib_name(n)) and ("osmocom" in txt.lower() or "-losmo" in txt):
                return ("remove", "pkg-config file of a GSM/Osmocom library", kind,
                        ["pkg-config file named by the sources" if n in self.pcs else "libosmo* pkg-config name",
                         "content mentions Osmocom"])
            return ("preserve", "pkg-config file with an Osmocom-like name, content does not confirm it", kind, []) \
                if is_gsm_lib_name(n) else None
        if rel.startswith("lib/systemd/system/"):
            if not name.endswith(".service"):
                return None
            txt = head(real, 8192)
            m = re.search(r"^ExecStart=\s*-?(\S+)", txt, re.M)
            exe = os.path.basename(m.group(1)) if m else ""
            if name in self.units or (exe and (exe in self.programs or exe.startswith("osmo-")) and
                                      name.startswith("osmo")):
                return ("remove", "systemd unit of a GSM/Osmocom program", kind, [f"ExecStart {exe}"])
            return None
        for ns in NAMESPACE_DIRS:
            if rel.startswith(ns + "/"):
                hrel = rel[len("include/"):] if ns == "include/osmocom" else None
                ev = ["Osmocom namespace directory " + ns]
                if hrel and hrel in self.headers:
                    ev.append("header path exists in the project sources")
                return ("remove", "file in an Osmocom namespace directory", kind, ev, {"needs_core": True})
        if rel.startswith("share/doc/"):
            comp = rel.split("/")[2] if rel.count("/") >= 2 else ""
            if comp in self.components:
                return ("remove", "documentation of a GSM component", kind, [f"share/doc/{comp}"],
                        {"needs_core": True})
            return None
        return None

    def plan_state(self):
        st = os.path.join(self.home, ".local/state/gsm-lab")
        if os.path.isdir(st) and not os.path.islink(st):
            entries = sorted(os.listdir(st))
            self.add(Item("state", st, "remove", "gsm-lab runtime state (run directories, run ledger, databases)",
                          kind="dir", evidence=["path reserved by gsm-lab (lab/docs/LAB.md)",
                                                "entries: " + (", ".join(entries) or "none")]))
        tx = os.path.join(self.home, ".config/tmuxinator")
        if os.path.isdir(tx):
            for n in sorted(os.listdir(tx)):
                p = os.path.join(tx, n)
                if not os.path.isfile(p) or os.path.islink(p):
                    continue
                txt = head(p, 512)
                if txt.startswith(TMUXINATOR_MARKER):
                    self.add(Item("state", p, "remove", "tmuxinator project generated by gsm-lab", evidence=[
                        "first line: " + TMUXINATOR_MARKER]))
                elif re.search(r"osmo-|osmocom|gsm-lab", txt, re.I):
                    self.add(Item("state", p, "preserve", "tmuxinator project mentioning Osmocom, not generated by "
                                  "gsm-lab (hand-written)"))

    def plan_temp(self):
        for t in self.temp_dirs:
            try:
                names = os.listdir(t)
            except OSError:
                continue
            for n in sorted(names):
                p = os.path.join(t, n)
                if not any(fnmatch.fnmatch(n, pat) for pat in TEMP_PATTERNS):
                    continue
                try:
                    st = os.lstat(p)
                except OSError:
                    continue
                if st.st_uid != self.uid:
                    self.add(Item("temp", p, "preserve", "owned by another user", kind="dir" if stat.S_ISDIR(
                        st.st_mode) else "file"))
                    continue
                self.add(Item("temp", p, "remove", "temporary leftover of the A-worker tests / snapshots",
                              kind="dir" if stat.S_ISDIR(st.st_mode) else "file", evidence=[f"name pattern in {t}"]))

    def plan_repos(self):
        for top, r in sorted(self.repos.items()):
            if not r["verified"]:
                # reported only when it looks related (by its own name or remotes); others are not listed at all
                if any(k in os.path.basename(top).lower() for k in ("osmo", "gsm")) or \
                        any("osmo" in u.lower() for u in r["urls"]):
                    self.add(Item("repo", top, "preserve", "not a verified GSM/Osmocom repository: " + r["why"],
                                  kind="worktree" if r["linked"] else "repo"))
                continue
            refs = backup_refs(r["gitdir"] if r["linked"] else r["commondir"])
            kind = "worktree" if r["linked"] else "repo"
            if refs:
                self.add(Item("repo", top, "protected", f"holds backup refs ({len(refs)}, e.g. "
                              f"{refs[0].split(': ')[-1]})", kind=kind, evidence=[r["why"]]))
                continue
            if not self.with_repo:
                self.add(Item("repo", top, "preserve", "repositories are kept without --repo", kind=kind,
                              evidence=[r["why"]]))
                continue
            work = local_work(top)
            if work and not self.discard:
                self.add(Item("repo", top, "preserve", "has local work: " + "; ".join(work) +
                              " (--discard-local-work removes it anyway)", kind=kind, evidence=[r["why"]]))
                continue
            self.add(Item("repo", top, "remove", "verified GSM/Osmocom " + ("worktree" if r["linked"] else
                                                                           "repository"), kind=kind,
                          evidence=[r["why"]] + (["local work discarded: " + "; ".join(work)] if work else []),
                          extra={"commondir": r["commondir"]}))
        for d, name in sorted(self.source_trees.items()):
            if self.in_any_repo(d):
                continue
            self.add(Item("repo", d, "remove" if self.with_repo else "preserve",
                          f"exported source tree of {name} (no .git)" if self.with_repo else
                          "source trees are kept without --repo", kind="dir",
                          evidence=["configure.ac AC_INIT " + name, ".tarball-version"]))

    # ---------------- safety checks over the whole plan
    def check_dependents(self):
        """A library is kept if a program or library that is NOT removed needs it."""
        removing = {i.path for i in self.items if i.action == "remove"}
        rm_dirs = [i.path for i in self.items if i.action == "remove" and i.kind in ("dir", "repo", "worktree")]
        sonames = {}
        for i in self.items:
            if i.action == "remove" and i.category == "install" and ".so" in os.path.basename(i.path):
                dyn = elf_dynamic(os.path.realpath(i.path))
                if dyn and dyn[0]:
                    sonames.setdefault(dyn[0], []).append(i)
        if not sonames:
            return
        for pfx in self.prefixes():
            for sub in ("bin", "sbin", "libexec", "lib", "lib64"):
                base = os.path.join(pfx, sub)
                if not os.path.isdir(base):
                    continue
                for p in list_files(base, 1):
                    if p in removing or any(under(p, d) for d in rm_dirs) or os.path.islink(p):
                        continue
                    dyn = elf_dynamic(p)
                    if not dyn:
                        continue
                    for n in dyn[1]:
                        for i in sonames.get(n, []):
                            if i.action == "remove":
                                i.action, i.reason = "preserve", f"still needed by {p}, which is not removed"

    def check_running(self):
        used = set()
        for pid in os.listdir("/proc"):
            if not pid.isdigit():
                continue
            try:
                used.add(os.path.realpath(f"/proc/{pid}/exe"))
            except OSError:
                pass
            try:
                with open(f"/proc/{pid}/maps") as f:
                    for line in f:
                        parts = line.split(None, 5)
                        if len(parts) == 6 and parts[5].startswith("/"):
                            used.add(parts[5].strip().replace(" (deleted)", ""))
            except OSError:
                pass
            try:
                used.add(os.path.realpath(f"/proc/{pid}/cwd"))
            except OSError:
                pass
        for i in self.items:
            if i.action != "remove":
                continue
            p = os.path.realpath(i.path) if i.kind not in ("dir", "repo", "worktree") else norm(i.path)
            busy = [u for u in used if u == p or (i.kind in ("dir", "repo", "worktree") and under(u, p))]
            if busy:
                i.action, i.reason = "preserve", f"in use by a running process ({busy[0]})"


# ------------------------------------------------------------------ helpers

def read_text(path, n=1 << 20):
    """Up to n characters of a text file ('' if unreadable); n=None: all of it."""
    try:
        with open(path, errors="replace") as f:
            return f.read() if n is None else f.read(n)
    except OSError:
        return ""


def head(path, n, binary=False):
    try:
        with open(path, "rb") as f:
            b = f.read(n)
        return b.decode("latin-1")
    except OSError:
        return ""


def list_files(base, depth):
    """Files and symbolic links below base: depth 1 = direct entries only, None = the whole tree. Never follows
    symbolic links (a linked directory is returned as an entry, not entered)."""
    out = []
    for d, dirs, files in os.walk(base, followlinks=False):
        out += [os.path.join(d, f) for f in files]
        out += [os.path.join(d, x) for x in dirs if os.path.islink(os.path.join(d, x))]
        dirs[:] = [] if depth == 1 else [x for x in dirs if not os.path.islink(os.path.join(d, x))]
    return out


def parse_remote(url):
    """(host, path) of a git remote URL: scheme://[user@]host[:port]/path, user@host:path, or a local path."""
    m = re.match(r"^[a-z][a-z0-9+.-]*://(?:[^@/]*@)?([^/:]+)(?::\d+)?/(.*)$", url, re.I)
    if m and not url.startswith("file://"):
        return m.group(1).lower(), m.group(2)
    m = re.match(r"^(?:[^@/]+@)?([^/:]+):(?!/)(.*)$", url)
    if m and not os.path.isabs(url):
        return m.group(1).lower(), m.group(2)
    return "", url[7:] if url.startswith("file://") else url


def ac_init_name(path):
    txt = read_text(path, 20000)
    m = re.search(r"AC_INIT\(\s*\[?([A-Za-z0-9_.+-]+)\]?", txt)
    return m.group(1) if m else None


def osmocom_configure(path):
    txt = read_text(path, None)
    return bool(re.search(r"osmocom|libosmocore|OSMO_|openbsc@lists", txt, re.I))


def config_status(path):
    """(srcdir, prefix) recorded in an autoconf config.status."""
    txt = read_text(path, 200000)
    if not txt:
        return None, None
    m = re.search(r"^ac_pwd='([^']*)'", txt, re.M)
    pwd_ = m.group(1) if m else os.path.dirname(path)
    m = re.search(r"^srcdir='([^']*)'", txt, re.M)
    srcdir = norm(os.path.join(pwd_, m.group(1))) if m else None
    m = re.search(r"--prefix=([^' ]+)", txt)
    prefix = norm(m.group(1)) if m else "/usr/local"
    return srcdir, prefix


def local_work(top):
    """What a removal would lose: uncommitted changes, stashes, commits on no remote (submodules included)."""
    work = []
    rc, out = git(["status", "--porcelain", "--ignore-submodules=none"], cwd=top)
    if rc != 0:
        return ["git status failed"]
    lines = [l for l in out.splitlines() if l.strip()]
    if lines:
        work.append(f"{len(lines)} uncommitted change(s)")
    rc, out = git(["stash", "list"], cwd=top)
    if out.strip():
        work.append(f"{len(out.splitlines())} stash entr(ies)")
    rc, out = git(["log", "--branches", "--not", "--remotes", "--format=%h", "-n", "50"], cwd=top)
    if out.strip():
        work.append(f"{len(out.splitlines())} commit(s) on no remote")
    rc, out = git(["log", "HEAD", "--not", "--remotes", "--format=%h", "-n", "50"], cwd=top)
    if rc == 0 and out.strip() and not any("on no remote" in w for w in work):
        work.append(f"{len(out.splitlines())} commit(s) of HEAD on no remote (detached)")
    rc, out = git(["submodule", "foreach", "--quiet", "--recursive",
                   "git log --branches --not --remotes --format=%h -n 1; git status --porcelain"], cwd=top)
    if rc == 0 and out.strip():
        work.append("local work in submodules")
    return work


